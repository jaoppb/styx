//! The certificate concern: one serving identity, its SPKI pin, and the startup ports that
//! produce it.
//!
//! No TLS-library type appears here. Certificates and the key travel as DER bytes; the
//! TLS adapter turns them into its own types.

use std::fmt;
use std::future::Future;
use std::path::Path;
use std::time::SystemTime;

use base64::engine::general_purpose::STANDARD;
use base64::Engine;

use crate::domain::error::CertificateError;
use crate::domain::tls::TlsConfig;

/// SHA-256 over the DER-encoded SubjectPublicKeyInfo of the serving certificate.
///
/// This is the value HTTP public-key pinning directives, `curl --pinnedpubkey sha256//…`
/// and DoT SPKI pinsets all consume, so its format is not free to choose. It is derived
/// from the public key, so it survives a re-issue of the same key and is safe to publish.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct SpkiPin {
    digest: [u8; 32],
}

impl SpkiPin {
    /// Hashes a DER-encoded SubjectPublicKeyInfo.
    ///
    /// # Errors
    /// Returns [`CertificateError::PinDerivationFailed`] for an empty input.
    pub fn from_spki_der(spki: &[u8]) -> Result<Self, CertificateError> {
        if spki.is_empty() {
            return Err(CertificateError::PinDerivationFailed);
        }
        let hashed = ring::digest::digest(&ring::digest::SHA256, spki);
        let digest = <[u8; 32]>::try_from(hashed.as_ref())
            .map_err(|_| CertificateError::PinDerivationFailed)?;
        Ok(Self { digest })
    }

    /// Standard base64 of the 32-byte digest.
    #[must_use]
    pub fn to_base64(&self) -> String {
        STANDARD.encode(self.digest)
    }

    /// The `pin-sha256="<base64>"` form pinning clients and RFC 7469 use.
    #[must_use]
    pub fn to_pin_directive(&self) -> String {
        format!("pin-sha256=\"{}\"", self.to_base64())
    }
}

impl fmt::Display for SpkiPin {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.to_pin_directive())
    }
}

impl fmt::Debug for SpkiPin {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "SpkiPin({})", self.to_base64())
    }
}

/// Where a certificate's validity window places `now`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ValidityState {
    /// Inside the window.
    Valid,
    /// Before `not_before`.
    NotYetValid,
    /// After `not_after`.
    Expired,
}

/// A certificate's `notBefore`..`notAfter` window.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ValidityWindow {
    /// Start of validity.
    pub not_before: SystemTime,
    /// End of validity.
    pub not_after: SystemTime,
}

impl ValidityWindow {
    /// Places `now` against the window. The caller passes the time; nothing here reads a
    /// clock.
    #[must_use]
    pub fn state_at(&self, now: SystemTime) -> ValidityState {
        if now < self.not_before {
            ValidityState::NotYetValid
        } else if now > self.not_after {
            ValidityState::Expired
        } else {
            ValidityState::Valid
        }
    }
}

/// How a private key is encoded inside its DER bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PrivateKeyEncoding {
    /// RSA, PKCS#1.
    Pkcs1,
    /// Elliptic curve, SEC1.
    Sec1,
    /// Any algorithm, PKCS#8.
    Pkcs8,
}

/// A private key's DER bytes. Its `Debug` rendering never shows them.
#[derive(Clone, PartialEq, Eq)]
pub struct PrivateKeyMaterial {
    encoding: PrivateKeyEncoding,
    der: Vec<u8>,
}

impl PrivateKeyMaterial {
    /// Wraps DER bytes of the given encoding.
    #[must_use]
    pub fn new(encoding: PrivateKeyEncoding, der: Vec<u8>) -> Self {
        Self { encoding, der }
    }

    /// The key's encoding.
    #[must_use]
    pub fn encoding(&self) -> PrivateKeyEncoding {
        self.encoding
    }

    /// The key's DER bytes, for the TLS adapter only.
    #[must_use]
    pub fn der(&self) -> &[u8] {
        &self.der
    }
}

impl fmt::Debug for PrivateKeyMaterial {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "PrivateKeyMaterial({:?}, <redacted>)", self.encoding)
    }
}

/// Which of the two sources produced the serving identity.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CertificateOrigin {
    /// Read from the operator's configured paths.
    OperatorSupplied,
    /// Generated by styx and persisted in the self-signed directory.
    SelfSigned,
}

impl CertificateOrigin {
    /// Stable label for log fields.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::OperatorSupplied => "operator-supplied",
            Self::SelfSigned => "self-signed",
        }
    }
}

/// The parts a [`ServingIdentity`] is assembled from.
#[derive(Debug, Clone)]
pub struct ServingIdentityParts {
    /// DER certificates, leaf first.
    pub chain: Vec<Vec<u8>>,
    /// The leaf's private key.
    pub key: PrivateKeyMaterial,
    /// The leaf's SPKI pin.
    pub pin: SpkiPin,
    /// The leaf's validity window.
    pub validity: ValidityWindow,
    /// The leaf's subject alternative names, as text.
    pub subject_names: Vec<String>,
    /// Which source produced it.
    pub origin: CertificateOrigin,
    /// `true` only on the boot that generated it.
    pub freshly_generated: bool,
}

/// The one certificate chain and key both encrypted listeners serve.
#[derive(Debug, Clone)]
pub struct ServingIdentity {
    parts: ServingIdentityParts,
}

impl ServingIdentity {
    /// Assembles an identity.
    ///
    /// # Errors
    /// Returns [`CertificateError::EmptyChain`] when `chain` holds no certificate.
    pub fn new(parts: ServingIdentityParts) -> Result<Self, CertificateError> {
        if parts.chain.is_empty() {
            return Err(CertificateError::EmptyChain);
        }
        Ok(Self { parts })
    }

    /// DER certificates, leaf first.
    #[must_use]
    pub fn chain(&self) -> &[Vec<u8>] {
        &self.parts.chain
    }

    /// The private key.
    #[must_use]
    pub fn key(&self) -> &PrivateKeyMaterial {
        &self.parts.key
    }

    /// The SPKI pin.
    #[must_use]
    pub fn pin(&self) -> SpkiPin {
        self.parts.pin
    }

    /// The validity window.
    #[must_use]
    pub fn validity(&self) -> ValidityWindow {
        self.parts.validity
    }

    /// Where the window places `now`.
    #[must_use]
    pub fn validity_state(&self, now: SystemTime) -> ValidityState {
        self.parts.validity.state_at(now)
    }

    /// Subject alternative names.
    #[must_use]
    pub fn subject_names(&self) -> &[String] {
        &self.parts.subject_names
    }

    /// Which source produced it.
    #[must_use]
    pub fn origin(&self) -> CertificateOrigin {
        self.parts.origin
    }

    /// `true` only on the boot that generated it.
    #[must_use]
    pub fn freshly_generated(&self) -> bool {
        self.parts.freshly_generated
    }
}

/// Startup port: hand the listeners one complete serving identity.
///
/// Obligation: return a complete identity or a typed error, never a partial one.
/// Implemented by: `application::certificate::CertificateProvisioner` (Phase 7) in
/// production; tests use the provisioner over fake loaders.
/// Why it exists: the listeners depend on "serving material", never on a filesystem, a
/// key encoding or a TLS library. Called once at startup, before any listener binds, and
/// never on the hot path.
pub trait ServingIdentityProvider: Send + Sync + 'static {
    /// Resolves the configured source into the identity to serve.
    fn resolve(
        &self,
        config: &TlsConfig,
    ) -> impl Future<Output = Result<ServingIdentity, CertificateError>> + Send;
}

/// Startup port: read an operator-supplied certificate chain and key.
///
/// Obligation: fail with an error naming the file at fault, and refuse a key that does
/// not match the leaf certificate, so a misconfiguration is one startup message rather
/// than a handshake failure repeated forever.
/// Implemented by: `infrastructure::cert_fs::FilesystemCertificateReader` (Phase 7).
/// Why it exists: keeps file I/O and PEM parsing out of `application`.
pub trait OperatorCertificateLoader: Send + Sync + 'static {
    /// Loads and checks the pair.
    fn load(
        &self,
        cert_path: &Path,
        key_path: &Path,
    ) -> impl Future<Output = Result<ServingIdentity, CertificateError>> + Send;
}

/// Startup port: the self-signed directory, read and written.
///
/// Obligation: `load_existing` never generates; `generate` writes the key owner-only and
/// returns an identity marked freshly generated; material found readable by group or
/// others is refused.
/// Implemented by: `infrastructure::cert_fs::SelfSignedGenerator` (Phase 7).
/// Why it exists: generation happens once and is reused, so the pin the operator
/// distributed stays valid across restarts.
pub trait SelfSignedStore: Send + Sync + 'static {
    /// Returns the persisted identity in `dir`, or `None` when there is none.
    fn load_existing(
        &self,
        dir: &Path,
    ) -> impl Future<Output = Result<Option<ServingIdentity>, CertificateError>> + Send;

    /// Generates, persists and returns a new identity valid from `now`.
    fn generate(
        &self,
        dir: &Path,
        names: &[String],
        now: SystemTime,
    ) -> impl Future<Output = Result<ServingIdentity, CertificateError>> + Send;
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use super::*;

    #[test]
    fn pin_directive_is_base64_sha256_of_the_spki() {
        // `printf 'spki' | openssl dgst -sha256 -binary | base64`
        let pin = SpkiPin::from_spki_der(b"spki").unwrap();
        assert_eq!(
            pin.to_pin_directive(),
            "pin-sha256=\"b+7MjBbFVR2f6z61934tp3O/aL2e+cUpJ86yyG5WiSs=\""
        );
        assert_eq!(pin.to_string(), pin.to_pin_directive());
        assert!(SpkiPin::from_spki_der(&[]).is_err());
    }

    #[test]
    fn validity_window_places_now() {
        let start = SystemTime::UNIX_EPOCH + Duration::from_secs(1000);
        let window = ValidityWindow {
            not_before: start,
            not_after: start + Duration::from_secs(100),
        };
        assert_eq!(
            window.state_at(start - Duration::from_secs(1)),
            ValidityState::NotYetValid
        );
        assert_eq!(window.state_at(start), ValidityState::Valid);
        assert_eq!(
            window.state_at(start + Duration::from_secs(101)),
            ValidityState::Expired
        );
    }

    #[test]
    fn debug_never_renders_key_bytes() {
        let key = PrivateKeyMaterial::new(PrivateKeyEncoding::Pkcs8, vec![0xAB; 4]);
        let rendered = format!("{key:?}");
        assert!(!rendered.contains("171"), "{rendered}");
        assert!(rendered.contains("redacted"), "{rendered}");
    }
}
